"""Generator registry and shared emission helpers.

A generator is a pure function::

    (Step, Plan) -> list[Artifact]

Pure in the strict sense: no clock, no randomness, no environment reads, no
filesystem access. Given the same step it must emit byte-identical artifacts
forever. Everything a generator is allowed to know arrives through its
arguments. This is what makes the ``strict`` rigor double-build check
meaningful -- if a generator cheats, the two runs disagree and the build fails.
"""

from __future__ import annotations

from typing import Callable, Protocol

from ..design import Plan, Step
from ..errors import GeneratorError
from ..transform import Artifact

BANNER = "Generated by forge from network intent. Do not edit by hand."


class Generator(Protocol):
    """Callable contract every generator satisfies."""

    def __call__(self, step: Step, plan: Plan) -> list[Artifact]: ...


_REGISTRY: dict[str, Generator] = {}


def register(name: str) -> Callable[[Generator], Generator]:
    """Decorator registering a generator under ``name``."""

    def decorate(func: Generator) -> Generator:
        if name in _REGISTRY:
            raise GeneratorError(f"generator {name!r} is already registered")
        _REGISTRY[name] = func
        return func

    return decorate


def get(name: str) -> Generator:
    try:
        return _REGISTRY[name]
    except KeyError:
        raise GeneratorError(
            f"unknown generator {name!r}; available: {', '.join(available())}"
        ) from None


def available() -> list[str]:
    return sorted(_REGISTRY)


# ---- emission helpers ----------------------------------------------------


def header(step: Step, plan: Plan) -> list[str]:
    """Standard provenance header.

    Every generated file records the intent digest it came from, so a reader
    can always trace a file back to the intent that justified it. The digest is
    content-derived, not a timestamp, so regenerating unchanged intent produces
    an unchanged header.
    """
    return [
        f'"""{step.node.description or step.node.id}',
        "",
        f"{BANNER}",
        "",
        f"node:    {step.node.id} ({step.node.kind})",
        f"intent:  {plan.intent.name}",
        f"digest:  {plan.intent.digest_hex}",
        '"""',
        "",
        "from __future__ import annotations",
        "",
    ]


def pascal(text: str) -> str:
    """snake_case -> PascalCase, deterministically."""
    return "".join(part[:1].upper() + part[1:] for part in text.split("_") if part)


def snake(text: str) -> str:
    """PascalCase -> snake_case."""
    out: list[str] = []
    for index, char in enumerate(text):
        if char.isupper() and index > 0 and not text[index - 1].isupper():
            out.append("_")
        out.append(char.lower())
    return "".join(out)


def docstring(lines: list[str], indent: str = "    ") -> list[str]:
    """Render a docstring block, escaping any embedded triple quotes."""
    safe = [line.replace('"""', "'''") for line in lines]
    if len(safe) == 1:
        return [f'{indent}"""{safe[0]}"""']
    body = [f'{indent}"""{safe[0]}']
    # Only insert the summary/body separator when the caller did not supply one,
    # otherwise the two stack up into a doubled blank line.
    rest = safe[1:]
    if rest and rest[0] != "":
        body.append("")
    body.extend(f"{indent}{line}".rstrip() for line in rest)
    body.append(f'{indent}"""')
    return body


def render(lines: list[str]) -> bytes:
    """Join lines into a UTF-8 file with exactly one trailing newline.

    Trailing whitespace is stripped and runs of blank lines collapsed, so
    formatting drift cannot change a digest.
    """
    cleaned: list[str] = []
    blanks = 0
    for line in lines:
        stripped = line.rstrip()
        if stripped == "":
            blanks += 1
            if blanks > 2:
                continue
        else:
            blanks = 0
        cleaned.append(stripped)
    while cleaned and cleaned[-1] == "":
        cleaned.pop()
    return ("\n".join(cleaned) + "\n").encode("utf-8")


def py_literal(value: object) -> str:
    """Render a JSON-ish value as a deterministic Python literal."""
    if isinstance(value, bool):
        return "True" if value else "False"
    if value is None:
        return "None"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(py_literal(item) for item in value) + "]"
    if isinstance(value, dict):
        inner = ", ".join(f"{py_literal(k)}: {py_literal(v)}" for k, v in sorted(value.items()))
        return "{" + inner + "}"
    raise GeneratorError(f"cannot render {type(value).__name__} as a Python literal")


